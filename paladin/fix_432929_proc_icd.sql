-- ЦЕПОЧКА БАГА (проверено по данным юзера + коду TC master):
--   432929 «Божественный молот» (пассивка, аура 42 PROC_TRIGGER_SPELL)
--     -> прокает 198034 «Божественный молот» (вращение)
--          -> E0: тик урона 198137 каждые 2000мс
--          -> E1: аура 395 -> AT 37932 -> "Invalid areatrigger create properties id"
--   Данные: ProcChance=101 (ВСЕГДА), ProcCharges=0, Cooldown=0, маски триггера
--   на ЛЮБОЙ каст -> после КАЖДОЙ способности молот перевешивается («3-4 бафа
--   каждые 1-2 сек»). Ограничители из ретейл-данных до TC не дошли
--   (spell_misc пуст), и генератор проков TC создал безусловный прок.
--
-- КАК РАБОТАЕТ ФИКС:
--   Строка в world.spell_proc имеет ПРИОРИТЕТ над автогенератором
--   (SpellMgr::LoadSpellProcs: "Data already present in DB, overwrites default
--   proc"). Мы наследуем триггер-маски и шанс из данных (нули = «взять из DBC»),
--   но ставим Cooldown = 1 час. Молот от проков фактически выключен;
--   легитимное поведение (молот от Темплар/ТДА) уже реализовано нашим кодом
--   партии 9 (spell_pal_divine_toll_templar_ex).
--
-- КАК СТАВИТЬ (Navicat):
--   1) правый клик по базе world -> Execute SQL File... -> этот файл -> Start.
--   2) Полный перезапуск worldserver.
--   3) В Server.log при старте допусти́мы WARN по 432929 про SpellPhaseMask /
--      ProcFlags — это ожидаемое следствие переопределения, не ошибка установки.
-- ПРОВЕРКА (Navicat, последний запрос): одна строка, Cooldown = 3600000.
-- ПРОВЕРКА В ИГРЕ: храмовник -> маунт/предмет/атаки 30-60 сек ->
--   бафы молота НЕ обновляются каждые 1-2 сек; строки AT 37932 не появляются.
--
-- ТЮНИНГ (по желанию, вместо 3600000):
--   30000  — молот прокает не чаще раза в 30 сек (виден, но не спамит);
--   вместе с Chance (поле 16) можно задать и шанс, напр. 20 = 20%.
-- ============================================================================

