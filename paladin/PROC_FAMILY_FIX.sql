-- PROC_FAMILY_FIX — ошибка в spell_proc ВСЕХ18 прок-строк паладина (26.09.2026)
-- Симптом: проки талантов класса не срабатывали (или срабатывали не полностью),
--   ошибок в логе НЕТ (SpellFamilyName=10 — валидное значение = SPELLFAMILY_DRUID).
-- Причина: в колонке SpellFamilyName стояло10 вместо0/2.
--   Код TC (SpellInfo::IsAffected): if (familyName != eventSpellInfo->SpellFamilyName)
--   return false — событие от паладинского спелла (family=2) отсекается фильтром.
--   TDB-эталон пишет0 (= «фильтр семейства выключен»).
-- Решение:
--   * строки с фам-масками (только Щит мстителя) -> SpellFamilyName=2 (PALADIN);
--   * все остальные (маски=0) -> SpellFamilyName=0 (TDB-стандарт).
-- Выполнить в HeidiSQL/mysql против БД **world**, затем перезапуск не обязателен
--   (spell_proc грузится при старте — перечитать можно `.reload spell_proc` или
--   перезапустить worldserver).
-- =============================================================================

--0) Контроль ДО (ожидаем18 строк, все SpellFamilyName=10):
SELECT SpellId, SpellFamilyName, SpellFamilyMask0, SpellFamilyMask1, SpellFamilyMask2, SpellFamilyMask3, ProcFlags, ProcFlags2, Chance
FROM spell_proc
WHERE SpellId IN (157047,267316,321136,326732,378285,387170,402912,403530,404357,406064,406157,406833,431474,469309,469883,1253174,1253598,1266308)
ORDER BY SpellId;

--1) Строки с фам-масками «Щит мстителя» (378285 Гнев Тира,469883 Очищающий огонь)
--   -> семейство PALADIN (2), чтобы маски [0x4000,0x0,0x2,0x0] вообще читались
UPDATE spell_proc SET SpellFamilyName = 2
WHERE SpellId IN (378285, 469883) AND SpellFamilyName <> 2;

--2) Остальные наши16 строк (маски=0) ->0 (выключить фильтр семейства, как в TDB)
UPDATE spell_proc SET SpellFamilyName = 0
WHERE SpellId IN (157047,267316,321136,326732,387170,402912,403530,404357,406064,406157,406833,431474,469309,1253174,1253598,1266308)
  AND SpellFamilyName <> 0;

--3) Контроль ПОСЛЕ (все18: SpellFamilyName =2 у378285/469883,0 у остальных):
SELECT SpellId, SpellFamilyName,
       CASE WHEN SpellId IN (378285,469883) THEN 'ОЖИДАЕМ2' ELSE 'ОЖИДАЕМ0' END AS expectation
FROM spell_proc
WHERE SpellId IN (157047,267316,321136,326732,378285,387170,402912,403530,404357,406064,406157,406833,431474,469309,469883,1253174,1253598,1266308)
ORDER BY SpellId;

--4) Бонус: чужие строки с подозрительным семейством (не0 и не2 — скорее всего та же болезнь):
SELECT * FROM spell_proc WHERE SpellFamilyName NOT IN (0,2);

