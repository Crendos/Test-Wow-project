-- CLASS_PALADIN = 2 — это id класса, не SpellFamilyName.
-- Живые проки паладина в дампе (54149, 85804, 196926, 64890, 28789) сидят на 10.
-- Этот файл теперь только возвращает 378285/469883 на 10. Маски=0 не трогает.
-- Выполнить в HeidiSQL/mysql против БД **world**, затем перезапуск не обязателен
