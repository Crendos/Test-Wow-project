-- 0) Контроль ДО (ожидаем18 строк, все SpellFamilyName=10):
SELECT SpellId, SpellFamilyName, SpellFamilyMask0, SpellFamilyMask1, SpellFamilyMask2, SpellFamilyMask3, ProcFlags, ProcFlags2, Chance
FROM spell_proc
WHERE SpellId IN (157047,267316,321136,326732,378285,387170,402912,403530,404357,406064,406157,406833,431474,469309,469883,1253174,1253598,1266308)
ORDER BY SpellId;

-- 1) Гнев Тира / Очищающий огонь -> семейство паладина 10
UPDATE spell_proc SET SpellFamilyName = 10
WHERE SpellId IN (378285, 469883) AND SpellFamilyName <> 10;

-- 2) Контроль ПОСЛЕ (10 у 378285/469883; у остальных с нулевыми масками оставляем 0)
SELECT SpellId, SpellFamilyName,
       CASE WHEN SpellId IN (378285,469883) THEN 'ОЖИДАЕМ10' ELSE 'как было' END AS expectation
FROM spell_proc
WHERE SpellId IN (157047,267316,321136,326732,378285,387170,402912,403530,404357,406064,406157,406833,431474,469309,469883,1253174,1253598,1266308)
ORDER BY SpellId;

-- 3) Семейство 2 быть не должно (unused). 10 — нормальный паладин, не ошибка.
SELECT SpellId, SpellFamilyName FROM spell_proc WHERE SpellFamilyName = 2;

